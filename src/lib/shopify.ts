const shopifyStoreDomain =
  process.env.NEXT_PUBLIC_SHOPIFY_STOREFRONT_DOMAIN ||
  process.env.NEXT_PUBLIC_SHOPIFY_STORE_DOMAIN;
const shopifyAccessToken =
  process.env.NEXT_PUBLIC_SHOPIFY_STOREFRONT_ACCESS_TOKEN;

if (!shopifyStoreDomain || !shopifyAccessToken) {
  logRune(KINETIC_RUNES.BYPASS, "Sovereign Mock Mode Activated (No credentials)");
} else {
  logRune(KINETIC_RUNES.ACTUATE, `Connecting to: ${shopifyStoreDomain}`);
}


async function ShopifyData<T>(
  query: string,
  variables?: Record<string, unknown>
): Promise<ShopifyResponse<T>> {
  if (!shopifyStoreDomain || !shopifyAccessToken) {
    console.warn("⚠️ Shopify credentials missing. Check your environment variables.");
    return {
      data: {} as T,
      errors: [{ message: "Shopify credentials missing" }]
    };
  }

  const endpoint = `https://${shopifyStoreDomain}/api/2023-10/graphql.json`;

  const requestOptions = {
    method: "POST",
    headers: {
      "X-Shopify-Storefront-Access-Token": shopifyAccessToken,
      Accept: "application/json",
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ query, variables }),
    next: { revalidate: 3600 },
  };

  try {
    const response = await fetch(endpoint, requestOptions);
    if (!response.ok) {
      const errorText = await response.text();
      console.error(`❌ Shopify Fetch Error (HTTP ${response.status}):`, errorText);
      return { data: {} as T, errors: [{ message: `HTTP Error ${response.status}` }] };
    }
    const data = await response.json();

    if (data.errors) {
      console.error(
        "❌ Shopify API Errors:",
        JSON.stringify(data.errors, null, 2)
      );
    }

    return data as ShopifyResponse<T>;
  } catch (error) {
    console.error("❌ Shopify Fetch Network Error:", error);
    // Return empty data instead of throwing to prevent crashing the app
    return { data: {} as T, errors: [{ message: "Network error fetching from Shopify" }] };
  }
}

